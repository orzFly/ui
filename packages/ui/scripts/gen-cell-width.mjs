// Regenerates src/lib/cell-width-table.ts from Unicode's EastAsianWidth.txt.
// Run with `node scripts/gen-cell-width.mjs` inside packages/ui; the output is
// checked in, so neither the build nor a consumer ever fetches it.
import { writeFileSync } from "node:fs";

const UNICODE_VERSION = "16.0.0";
const SOURCE = `https://www.unicode.org/Public/${UNICODE_VERSION}/ucd/EastAsianWidth.txt`;
const OUT = new URL("../src/lib/cell-width-table.ts", import.meta.url);

const response = await fetch(SOURCE);
if (!response.ok) throw new Error(`${SOURCE}: HTTP ${response.status}`);
const text = await response.text();

const ranges = [];
for (const raw of text.split("\n")) {
  const line = raw.replace(/#.*/, "").trim();
  if (!line) continue;
  const [span, width] = line.split(";").map((part) => part.trim());
  if (width !== "W" && width !== "F") continue;
  const [from, to = from] = span
    .split("..")
    .map((hex) => Number.parseInt(hex, 16));
  const last = ranges.at(-1);
  if (last && last[1] + 1 >= from) last[1] = Math.max(last[1], to);
  else ranges.push([from, to]);
}

const hex = (n) => `0x${n.toString(16)}`;
const PER_LINE = 4;
const rows = [];
for (let i = 0; i < ranges.length; i += PER_LINE) {
  const pairs = ranges
    .slice(i, i + PER_LINE)
    .map(([a, b]) => `${hex(a)}, ${hex(b)},`);
  rows.push(`  ${pairs.join(" ")}`);
}

writeFileSync(
  OUT,
  `// Generated by scripts/gen-cell-width.mjs from Unicode ${UNICODE_VERSION}
// EastAsianWidth.txt (W and F, adjacent ranges merged). Do not edit by hand.

/** East Asian Wide and Fullwidth code points, as sorted inclusive \`[from, to]\` pairs. */
// biome-ignore format: one range pair per column keeps the table scannable.
export const WIDE = Uint32Array.of(
${rows.join("\n")}
);
`,
);
console.log(`${ranges.length} ranges → ${OUT.pathname}`);
