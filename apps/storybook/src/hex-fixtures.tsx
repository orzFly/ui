const TEXT = new TextEncoder().encode(
  "The quick brown fox jumps over the lazy dog.\r\n",
);

/** The byte at `offset`: zero runs, ASCII runs and noise, so every glyph kind shows. */
export function syntheticByte(offset: number): number {
  const block = Math.floor(offset / 16);
  const kind = block % 11;
  if (kind === 3) return 0;
  if (kind === 6 || kind === 7) return TEXT[offset % TEXT.length] as number;
  let x = (block ^ 0x9e3779b9) >>> 0;
  x ^= x << 13;
  x ^= x >>> 17;
  x ^= x << 5;
  return ((x >>> 0) + (offset & 15) * 0x3d) & 0xff;
}

export function syntheticBytes(size: number): Uint8Array {
  const bytes = new Uint8Array(size);
  for (let i = 0; i < size; i++) bytes[i] = syntheticByte(i);
  return bytes;
}

/** A paged source over `size` generated bytes that answers after `latencyMs`. */
export function syntheticSource({
  size,
  latencyMs,
  failPage,
  pageSize = 65536,
}: {
  size: number;
  latencyMs: number;
  /** Every read touching this page of `pageSize` bytes fails. */
  failPage?: number;
  pageSize?: number;
}): ByteSource {
  return {
    size,
    read(offset, length, signal) {
      return new Promise((resolve, reject) => {
        const timer = setTimeout(() => {
          signal?.removeEventListener("abort", onAbort);
          const end = Math.min(size, offset + length);
          if (
            failPage !== undefined &&
            Math.floor(offset / pageSize) <= failPage &&
            Math.floor((end - 1) / pageSize) >= failPage
          ) {
            reject(new Error(`Page ${failPage} is unreadable`));
            return;
          }
          const bytes = new Uint8Array(Math.max(0, end - offset));
          for (let i = 0; i < bytes.length; i++) {
            bytes[i] = syntheticByte(offset + i);
          }
          resolve(bytes);
        }, latencyMs);
        const onAbort = () => {
          clearTimeout(timer);
          reject(signal?.reason);
        };
        signal?.addEventListener("abort", onAbort, { once: true });
      });
    },
  };
}

// The --hex-* defaults sit on .orz-hex itself, so an override has to reach
// that element rather than an ancestor.
const FRAME_CSS = `.hex-frame :is(.orz-hex, .orz-hex-inspector) {
  --hex-font: "JetBrains Mono Variable", monospace;
}`;

/** Loads the hex stylesheet and the demo's monospace font around a story. */
export function HexFrame({
  children,
  height,
}: {
  children: ReactNode;
  /** A fixed frame height, for a view that fills its parent. */
  height?: number;
}) {
  return (
    <div className="hex-frame" style={{ height }}>
      <style>{FRAME_CSS}</style>
      {children}
    </div>
  );
}
